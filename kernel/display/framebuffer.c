/* =========================================================================
 * Text rendering
 * ========================================================================= */

int FB_CharWidth(void)  { return 8; }
int FB_CharHeight(void) { return 16; }

void FB_PutChar(int x, int y, char ch, uint32_t fg, uint32_t bg)
{
    if (!g_fb.valid) return;
    uint8_t c = (uint8_t)ch;
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *glyph = g_font8x16[c - 0x20];
    for (int row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            uint32_t colour = (bits & (0x80 >> col)) ? fg : bg;
            FB_PutPixel(x + col, y + row, colour);
        }
    }
}

void FB_PutStr(int x, int y, const char *s, uint32_t fg, uint32_t bg)
{
    int cx = x;
    while (*s) {
        if (*s == '\n') { cx = x; y += 16; }
        else            { FB_PutChar(cx, y, *s, fg, bg); cx += 8; }
        s++;
    }
}

void FB_PutStrCentred(int rx, int ry, int rw, int rh,
                      const char *s, uint32_t fg, uint32_t bg)
{
    int len = 0;
    for (const char *p = s; *p; p++) len++;
    int tw = len * 8;
    int th = 16;
    int tx = rx + (rw - tw) / 2;
    int ty = ry + (rh - th) / 2;
    FB_PutStr(tx, ty, s, fg, bg);
}

