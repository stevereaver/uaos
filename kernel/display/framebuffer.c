#define FONT_SMALL_OVERRIDE_COUNT \
    (int)(sizeof(g_font_small_overrides) / sizeof(g_font_small_overrides[0]))

static void build_small_font(void)
{
    for (int g = 0; g < 95; g++) {
        /* Sample the 8x16 glyph's odd rows (1,3,5,...,15) — a reasonable
         * midpoint decimation that keeps stems/serifs visible at half
         * height until real Topaz glyphs are substituted in via the
         * override table above. */
        for (int r = 0; r < 8; r++)
            g_font_small[g][r] = g_font8x16[g][r * 2 + 1];
    }
    for (int i = 1; i < FONT_SMALL_OVERRIDE_COUNT; i++) {
        uint8_t code = g_font_small_overrides[i].code;
        if (code < 0x20 || code > 0x7E) continue;
        for (int r = 0; r < 8; r++)
            g_font_small[code - 0x20][r] = g_font_small_overrides[i].rows[r];
    }
    g_font_small_ready = 1;
}

int FB_CharWidthSmall(void)  { return 8; }
int FB_CharHeightSmall(void) { return 8; }

void FB_PutCharSmall(int x, int y, char ch, uint32_t fg, uint32_t bg)
{
    if (!g_fb.valid) return;
    if (!g_font_small_ready) build_small_font();
    uint8_t c = (uint8_t)ch;
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *glyph = g_font_small[c - 0x20];

    if (g_drawing) {
        for (int row = 0; row < 8; row++) {
            int py = y + row;
            if ((unsigned)py >= BB_MAX_H) break;
            uint8_t bits = glyph[row];
            uint32_t *dst = g_backbuf[py];
            for (int col = 0; col < 8; col++) {
                int px = x + col;
                if ((unsigned)px < BB_MAX_W)
                    dst[px] = (bits & (0x80 >> col)) ? fg : bg;
            }
        }
        dirty_add(x, y, x + 8, y + 8);
        return;
    }

    uint8_t *base = (uint8_t *)(uintptr_t)g_fb.phys_addr;
    if (g_fb.bpp == 32) {
        for (int row = 0; row < 8; row++) {
            int py = y + row;
            if (py < 0 || (unsigned)py >= g_fb.height) continue;
            uint8_t bits = glyph[row];
            uint32_t *dst = (uint32_t *)(base + (uint32_t)py * g_fb.pitch);
            for (int col = 0; col < 8; col++) {
                int px = x + col;
                if (px < 0 || (unsigned)px >= g_fb.width) continue;
                dst[px] = (bits & (0x80 >> col)) ? fg : bg;
            }
        }
    } else {
        for (int row = 0; row < 8; row++) {
            int py = y + row;
            if (py < 0 || (unsigned)py >= g_fb.height) continue;
            uint8_t bits = glyph[row];
            uint8_t *dst = base + (uint32_t)py * g_fb.pitch;
            for (int col = 0; col < 8; col++) {
                int px = x + col;
                if (px < 0 || (unsigned)px >= g_fb.width) continue;
                uint32_t colour = (bits & (0x80 >> col)) ? fg : bg;
                uint8_t *p = dst + px * 3;
                p[0] = (uint8_t)(colour & 0xFF);
                p[1] = (uint8_t)((colour >> 8) & 0xFF);
                p[2] = (uint8_t)((colour >> 16) & 0xFF);
            }
        }
    }
}

void FB_PutStrSmall(int x, int y, const char *s, uint32_t fg, uint32_t bg)
{
    int cx = x;
    while (*s) {
        if (*s == '\n') { cx = x; y += 8; }
        else            { FB_PutCharSmall(cx, y, *s, fg, bg); cx += 8; }
        s++;
    }
}

void FB_PutStrSmallCentred(int rx, int ry, int rw, int rh,
                           const char *s, uint32_t fg, uint32_t bg)
{
    int len = 0;
    for (const char *p = s; *p; p++) len++;
    /* B5: truncate to the rect so long titles don't overdraw the zoom/depth
     * gadgets or bleed past the window edge. */
    int max_chars = rw / 8;
    if (max_chars <= 0) return;
    if (len > max_chars) len = max_chars;
    int tw = len * 8;
    int th = 8;
    int tx = rx + (rw - tw) / 2;
    int ty = ry + (rh - th) / 2;
    if (tx < rx) tx = rx;
    for (int i = 0; i < len; i++)
        FB_PutCharSmall(tx + i * 8, ty, s[i], fg, bg);
}
