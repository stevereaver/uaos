/* framebuffer.c — UAOS Linear Framebuffer Driver
 *
 * Parses the Multiboot2 framebuffer tag and provides pixel primitives and
 * an 8×16 bitmap font renderer.  Supports 32bpp and 24bpp linear framebuffers
 * as provided by GOP (UEFI) or VESA BIOS.
 */

#include "framebuffer.h"
#include <stdint.h>
#include <stddef.h>

/* =========================================================================
 * Global framebuffer state
 * ========================================================================= */

FbState g_fb = { 0, 0, 0, 0, 0, 0 };

/* =========================================================================
 * Back buffer for flicker-free double buffering
 * Max 1280×1024 @ 32bpp = 5 MB in BSS
 * ========================================================================= */
#define BB_MAX_W 1280
#define BB_MAX_H 1024
static uint32_t g_backbuf[BB_MAX_H][BB_MAX_W];
static int g_drawing = 0;  /* 1 = drawing to back buffer, 0 = direct */

void FB_BeginDraw(void)
{
    g_drawing = 1;
}

int FB_IsDrawing(void)
{
    return g_drawing;
}

uint32_t FB_GetPixel(int x, int y)
{
    if ((unsigned)x >= BB_MAX_W || (unsigned)y >= BB_MAX_H) return 0;
    if (g_drawing) return g_backbuf[y][x];
    if (!g_fb.valid) return 0;
    uint8_t *base = (uint8_t *)(uintptr_t)g_fb.phys_addr;
    if (g_fb.bpp == 32) {
        uint32_t *p = (uint32_t *)(base + (uint32_t)y * g_fb.pitch + (uint32_t)x * 4);
        return *p;
    } else {
        uint8_t *p = base + (uint32_t)y * g_fb.pitch + (uint32_t)x * 3;
        return (uint32_t)p[2] << 16 | (uint32_t)p[1] << 8 | p[0];
    }
}

void FB_Flip(void)
{
    if (!g_fb.valid || !g_drawing) return;
    uint8_t *dst = (uint8_t *)(uintptr_t)g_fb.phys_addr;
    uint32_t W = g_fb.width  < BB_MAX_W ? g_fb.width  : BB_MAX_W;
    uint32_t H = g_fb.height < BB_MAX_H ? g_fb.height : BB_MAX_H;
    if (g_fb.bpp == 32) {
        for (uint32_t y = 0; y < H; y++) {
            uint32_t *row_dst = (uint32_t *)(dst + y * g_fb.pitch);
            uint32_t *row_src = g_backbuf[y];
            for (uint32_t x = 0; x < W; x++)
                row_dst[x] = row_src[x];
        }
    } else {
        for (uint32_t y = 0; y < H; y++) {
            uint8_t *row_dst = dst + y * g_fb.pitch;
            uint32_t *row_src = g_backbuf[y];
            for (uint32_t x = 0; x < W; x++) {
                uint32_t c = row_src[x];
                row_dst[x*3+0] = (uint8_t)(c & 0xFF);
                row_dst[x*3+1] = (uint8_t)((c >> 8) & 0xFF);
                row_dst[x*3+2] = (uint8_t)((c >> 16) & 0xFF);
            }
        }
    }
    g_drawing = 0;
}

/* =========================================================================
 * Multiboot2 tag parsing
 * ========================================================================= */

/* Multiboot2 tag header (all tags share this prefix) */
typedef struct __attribute__((packed)) {
    uint32_t type;
    uint32_t size;
} Mb2TagHdr;

/* Multiboot2 framebuffer tag (type 8) */
typedef struct __attribute__((packed)) {
    uint32_t type;           /* = 8                        */
    uint32_t size;
    uint64_t framebuffer_addr;
    uint32_t framebuffer_pitch;
    uint32_t framebuffer_width;
    uint32_t framebuffer_height;
    uint8_t  framebuffer_bpp;
    uint8_t  framebuffer_type;   /* 1 = RGB                */
    uint16_t reserved;
} Mb2TagFb;

/* Multiboot2 info header */
typedef struct __attribute__((packed)) {
    uint32_t total_size;
    uint32_t reserved;
} Mb2InfoHdr;

void FB_Init(uint32_t mb2_info_phys)
{
    if (mb2_info_phys == 0) return;

    Mb2InfoHdr *hdr = (Mb2InfoHdr *)(uintptr_t)mb2_info_phys;
    uint8_t *p   = (uint8_t *)(uintptr_t)(mb2_info_phys + 8);
    uint8_t *end = (uint8_t *)(uintptr_t)(mb2_info_phys + hdr->total_size);

    while (p < end) {
        Mb2TagHdr *tag = (Mb2TagHdr *)p;
        if (tag->type == 0) break;           /* end tag */

        if (tag->type == 8) {                /* framebuffer tag */
            Mb2TagFb *fb = (Mb2TagFb *)p;
            if (fb->framebuffer_type == 1 && /* RGB mode */
                (fb->framebuffer_bpp == 32 || fb->framebuffer_bpp == 24)) {
                g_fb.phys_addr = fb->framebuffer_addr;
                g_fb.width     = fb->framebuffer_width;
                g_fb.height    = fb->framebuffer_height;
                g_fb.pitch     = fb->framebuffer_pitch;
                g_fb.bpp       = fb->framebuffer_bpp;
                g_fb.valid     = 1;
            }
            break;
        }

        /* Tags are aligned to 8 bytes */
        uint32_t aligned = (tag->size + 7) & ~7U;
        p += aligned ? aligned : 8;
    }
}

/* =========================================================================
 * Internal pixel write helpers
 * ========================================================================= */

static inline void put_pixel32(uint8_t *base, uint32_t pitch,
                                int x, int y, uint32_t colour)
{
    if (g_drawing) {
        if ((unsigned)x < BB_MAX_W && (unsigned)y < BB_MAX_H)
            g_backbuf[y][x] = colour;
        return;
    }
    uint32_t *px = (uint32_t *)(base + (uint32_t)y * pitch + (uint32_t)x * 4);
    *px = colour;
}

static inline void put_pixel24(uint8_t *base, uint32_t pitch,
                                int x, int y, uint32_t colour)
{
    if (g_drawing) {
        if ((unsigned)x < BB_MAX_W && (unsigned)y < BB_MAX_H)
            g_backbuf[y][x] = colour;
        return;
    }
    uint8_t *px = base + (uint32_t)y * pitch + (uint32_t)x * 3;
    px[0] = (uint8_t)(colour & 0xFF);
    px[1] = (uint8_t)((colour >> 8) & 0xFF);
    px[2] = (uint8_t)((colour >> 16) & 0xFF);
}

/* =========================================================================
 * Public drawing primitives
 * ========================================================================= */

void FB_PutPixel(int x, int y, uint32_t colour)
{
    if (!g_fb.valid) return;
    if (x < 0 || y < 0 || (unsigned)x >= g_fb.width || (unsigned)y >= g_fb.height) return;
    uint8_t *base = (uint8_t *)(uintptr_t)g_fb.phys_addr;
    if (g_fb.bpp == 32) put_pixel32(base, g_fb.pitch, x, y, colour);
    else                put_pixel24(base, g_fb.pitch, x, y, colour);
}

void FB_DrawHLine(int x, int y, int len, uint32_t colour)
{
    if (!g_fb.valid) return;
    if (y < 0 || (unsigned)y >= g_fb.height) return;
    /* Clip x range to [0, width) */
    int x0 = x < 0 ? 0 : x;
    int x1 = x + len;
    if (x1 > (int)g_fb.width) x1 = (int)g_fb.width;
    if (x0 >= x1) return;
    uint8_t *base = (uint8_t *)(uintptr_t)g_fb.phys_addr;
    for (int px = x0; px < x1; px++) {
        if (g_fb.bpp == 32) put_pixel32(base, g_fb.pitch, px, y, colour);
        else                put_pixel24(base, g_fb.pitch, px, y, colour);
    }
}

void FB_DrawVLine(int x, int y, int len, uint32_t colour)
{
    if (!g_fb.valid) return;
    if (x < 0 || (unsigned)x >= g_fb.width) return;
    /* Clip y range to [0, height) */
    int y0 = y < 0 ? 0 : y;
    int y1 = y + len;
    if (y1 > (int)g_fb.height) y1 = (int)g_fb.height;
    if (y0 >= y1) return;
    uint8_t *base = (uint8_t *)(uintptr_t)g_fb.phys_addr;
    for (int py = y0; py < y1; py++) {
        if (g_fb.bpp == 32) put_pixel32(base, g_fb.pitch, x, py, colour);
        else                put_pixel24(base, g_fb.pitch, x, py, colour);
    }
}

void FB_FillRect(int x, int y, int w, int h, uint32_t colour)
{
    if (!g_fb.valid || w <= 0 || h <= 0) return;
    /* Clip rect to framebuffer bounds */
    int x0 = x < 0 ? 0 : x;
    int y0 = y < 0 ? 0 : y;
    int x1 = x + w; if (x1 > (int)g_fb.width)  x1 = (int)g_fb.width;
    int y1 = y + h; if (y1 > (int)g_fb.height) y1 = (int)g_fb.height;
    if (x0 >= x1 || y0 >= y1) return;
    for (int row = y0; row < y1; row++)
        FB_DrawHLine(x0, row, x1 - x0, colour);
}

void FB_DrawRect(int x, int y, int w, int h, uint32_t colour)
{
    FB_DrawHLine(x,         y,         w, colour);
    FB_DrawHLine(x,         y + h - 1, w, colour);
    FB_DrawVLine(x,         y,         h, colour);
    FB_DrawVLine(x + w - 1, y,         h, colour);
}

