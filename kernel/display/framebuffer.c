/* framebuffer.c — UAOS Linear Framebuffer Driver
 *
 * Parses the Multiboot2 framebuffer tag and provides pixel primitives and
 * an 8×16 bitmap font renderer.  Supports 32bpp and 24bpp linear framebuffers
 * as provided by GOP (UEFI) or VESA BIOS.
 */

